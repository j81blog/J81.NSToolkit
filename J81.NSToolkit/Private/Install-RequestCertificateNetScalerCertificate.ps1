function Install-RequestCertificateNetScalerCertificate {
<#
    .SYNOPSIS
        Installs or updates a requested certificate on a NetScaler appliance.

    .DESCRIPTION
        Uploads the PFX generated by Posh-ACME to /nsconfig/ssl and creates or updates
        the target sslcertkey. Existing certkeys are updated by using the generated
        Invoke-NSChangeSslcertkey wrapper, which maps to the Nitro
        POST sslcertkey?action=update operation.

    .PARAMETER NSSession
        Existing NetScaler session returned by Connect-NSNode.

    .PARAMETER Settings
        Normalized request settings object. SaveADCConfig is read from this object.

    .PARAMETER Request
        Certificate request object containing CN and optional CertKeyNameToUpdate values.

    .PARAMETER Certificate
        Posh-ACME certificate object containing the generated PFX path.

    .PARAMETER PfxSecret
        Secure string containing the PFX password.

    .PARAMETER IsProduction
        Indicates that the certificate came from a production ACME endpoint. Non-production
        certificates receive a TST- prefix for the NetScaler certkey and uploaded PFX name.

    .NOTES
        Function  : Install-RequestCertificateNetScalerCertificate
        Author    : John Billekens
        Copyright : Copyright (c) John Billekens Consultancy
        Version   : 2026.0525.2137
#>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [object]$NSSession,

        [Parameter(Mandatory)]
        [object]$Settings,

        [Parameter(Mandatory)]
        [object]$Request,

        [Parameter(Mandatory)]
        [object]$Certificate,

        [Parameter(Mandatory)]
        [securestring]$PfxSecret,

        [switch]$IsProduction
    )

    $PlainPfx = ConvertFrom-RequestCertificateLegacySecret -Object $PfxSecret -AsClearText
    $CertNameBase = if ($Request.CertKeyNameToUpdate) {
        $Request.CertKeyNameToUpdate
    } else {
        $Request.CN -replace '[^a-zA-Z0-9_.=@:-]', '_'
    }

    if (-not $IsProduction -and $CertNameBase -notlike 'TST-*') {
        $CertKeyName = "TST-$CertNameBase"
    } else {
        $CertKeyName = $CertNameBase
    }

    $PfxPath = if ($Certificate.PfxFullChain) {
        $Certificate.PfxFullChain
    } elseif ($Certificate.PfxFile) {
        $Certificate.PfxFile
    } else {
        $Certificate.PfxFile
    }

    if (-not (Test-Path -LiteralPath $PfxPath)) {
        throw "PFX file not found: $PfxPath"
    }

    $PfxFileName = (Split-Path -Leaf $PfxPath) -replace '[^a-zA-Z0-9_.-]', '_'
    if (-not $IsProduction -and $PfxFileName -notlike 'TST-*') {
        $PfxFileName = "TST-$PfxFileName"
    }

    Copy-RequestCertificateNetScalerFile -NSSession $NSSession -Path $PfxPath -FileName $PfxFileName

    try {
        $Existing = Invoke-NSGetSslcertkey -NSSession $NSSession -Certkey $CertKeyName
    } catch {
        if ($_.Exception.Message -match '404|Not Found|No such resource|Certificate does not exist|\[258\]|\[1540\]') {
            $Existing = $null
        } else {
            throw
        }
    }

    if ($Existing) {
        Write-RequestCertificateLog Info 'Deploy' "Updating NetScaler SSL certkey '$CertKeyName'."
        $ChangeParams = @{
            NSSession = $NSSession
            Certkey   = $CertKeyName
            Cert      = $PfxFileName
            Key       = $PfxFileName
            Inform    = 'PFX'
            Password  = $true
            Passplain = $PlainPfx
        }
        Invoke-NSChangeSslcertkey @ChangeParams | Out-Null
    } else {
        Write-RequestCertificateLog Info 'Deploy' "Creating NetScaler SSL certkey '$CertKeyName'."
        $AddParams = @{
            NSSession = $NSSession
            Certkey   = $CertKeyName
            Cert      = $PfxFileName
            Key       = $PfxFileName
            Inform    = 'PFX'
            Password  = $true
            Passplain = $PlainPfx
        }
        Invoke-NSAddSslcertkey @AddParams | Out-Null
    }

    if ($Settings.SaveADCConfig) {
        Invoke-NSSaveNsconfig -NSSession $NSSession | Out-Null
    }

    [pscustomobject]@{
        CertKeyName = $CertKeyName
        PfxFileName = $PfxFileName
        PfxPath     = $PfxPath
    }
}
